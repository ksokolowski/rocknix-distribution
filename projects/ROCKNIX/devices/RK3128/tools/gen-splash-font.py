"""Write splash-font.h (ASCII 32-126) from Linux lib/fonts/font_8x16.c.

Usage: gen-splash-font.py KERNEL_FONT_8x16_C OUTPUT_H
The glyph data is GPL-2.0 (Linux kernel); the header keeps that notice.
"""
import re
import sys

src = open(sys.argv[1]).read()
body = re.sub(r"/\*.*?\*/", "", src.split("fontdata_8x16 = {", 1)[1], flags=re.S)
glyphs = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{2})", body)]
# Comments label each glyph with its code in hex; they are stripped above.
assert len(glyphs) == 256 * 16, len(glyphs)
rows = []
for ch in range(32, 127):
    rows.append("\t{" + ", ".join(f"0x{b:02x}" for b in glyphs[ch * 16:ch * 16 + 16]) + "},")
open(sys.argv[2], "w").write(
    "/* SPDX-License-Identifier: GPL-2.0 */\n"
    "/* 8x16 glyphs for ASCII 32-126 from Linux lib/fonts/font_8x16.c. */\n"
    "/* Generated by tools/gen-splash-font.py; do not edit. */\n"
    "#ifndef SPLASH_FONT_H\n#define SPLASH_FONT_H\n#include <stdint.h>\n"
    "static const uint8_t splash_font[95][16] = {\n" + "\n".join(rows) + "\n};\n#endif\n")
