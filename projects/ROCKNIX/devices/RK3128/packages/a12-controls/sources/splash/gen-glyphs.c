// Build-time tool: render a TrueType font (ES's) with FreeType into a glyph
// table header for the initramfs status screen, which has no FreeType
// (TEST_LOG test 61). The size and loads match splash-ttf.c, so
// splash-atlas.c draws the same pixels.
//   gen-glyphs FONT.ttf OUTPUT.h
#include <stdio.h>
#include <stdlib.h>
#include <ft2build.h>
#include FT_FREETYPE_H
#include "splash-draw.h"

int main(int argc, char **argv)
{
	FT_Library library;
	FT_Face face;
	/* splash-ttf.c: glyphs three quarters of the 16 * scale text row. */
	int pixel_height = 16 * SPLASH_TEXT_SCALE * 3 / 4;
	unsigned int offset = 0;

	if (argc != 3 || FT_Init_FreeType(&library) || FT_New_Face(library, argv[1], 0, &face) ||
	    FT_Set_Pixel_Sizes(face, 0, (FT_UInt)pixel_height)) {
		fprintf(stderr, "usage: gen-glyphs FONT.ttf OUTPUT.h\n");
		return 1;
	}
	FILE *out = fopen(argv[2], "w");
	if (!out)
		return 1;
	fprintf(out, "/* Generated by gen-glyphs from %s at %d px; do not edit. */\n", argv[1], pixel_height);
	fprintf(out, "#ifndef SPLASH_GLYPHS_H\n#define SPLASH_GLYPHS_H\n#include <stdint.h>\n");
	fprintf(out, "#define SPLASH_GLYPH_ASCENDER %ld\n#define SPLASH_GLYPH_DESCENDER %ld\n",
		face->size->metrics.ascender >> 6, -face->size->metrics.descender >> 6);
	fprintf(out, "struct splash_glyph { int16_t left, top, advance_load, advance_render; "
		     "uint16_t width, rows; uint32_t offset; };\n");
	fprintf(out, "static const struct splash_glyph splash_glyphs[95] = {\n");
	for (int ch = 32; ch < 127; ch++) {
		/* splash-ttf.c measures with FT_LOAD_DEFAULT and draws with FT_LOAD_RENDER. */
		long advance_load = FT_Load_Char(face, (FT_ULong)ch, FT_LOAD_DEFAULT) ? 0 : face->glyph->advance.x >> 6;
		if (FT_Load_Char(face, (FT_ULong)ch, FT_LOAD_RENDER)) {
			fprintf(out, "\t{ 0, 0, %ld, 0, 0, 0, %u },\n", advance_load, offset);
			continue;
		}
		FT_GlyphSlot g = face->glyph;
		fprintf(out, "\t{ %d, %d, %ld, %ld, %u, %u, %u },\n", g->bitmap_left, g->bitmap_top, advance_load,
			g->advance.x >> 6, g->bitmap.width, g->bitmap.rows, offset);
		offset += g->bitmap.width * g->bitmap.rows;
	}
	fprintf(out, "};\nstatic const uint8_t splash_glyph_px[%u] = {", offset ? offset : 1);
	unsigned int n = 0;
	for (int ch = 32; ch < 127; ch++) {
		if (FT_Load_Char(face, (FT_ULong)ch, FT_LOAD_RENDER))
			continue;
		FT_GlyphSlot g = face->glyph;
		for (unsigned int row = 0; row < g->bitmap.rows; row++)
			for (unsigned int col = 0; col < g->bitmap.width; col++)
				fprintf(out, "%s%u,", n++ % 24 ? "" : "\n\t",
					g->bitmap.buffer[row * (unsigned int)g->bitmap.pitch + col]);
	}
	fprintf(out, "%s\n};\n#endif\n", offset ? "" : "0");
	return fclose(out) ? 1 : 0;
}
